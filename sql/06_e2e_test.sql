USE WAREHOUSE ENERGY_WH;
USE DATABASE ENERGY_DB;

SET run_date = '2026-10-07';
SET expected_intervals = 96;   -- use 92 on the spring DST day and 100 on the autumn one

WITH counts AS (
    SELECT 'LOAD' AS DATASET, COUNTRY_CODE, COUNT(DISTINCT TIMESTAMP) AS INTERVALS
    FROM RAW.LOAD
    WHERE TO_DATE(CONVERT_TIMEZONE('Europe/Budapest', TIMESTAMP)) = $run_date
    GROUP BY COUNTRY_CODE
    UNION ALL
    SELECT 'LOAD_FORECAST', COUNTRY_CODE, COUNT(DISTINCT TIMESTAMP)
    FROM RAW.LOAD_FORECAST
    WHERE TO_DATE(CONVERT_TIMEZONE('Europe/Budapest', TIMESTAMP)) = $run_date
    GROUP BY COUNTRY_CODE
    UNION ALL
    SELECT 'GENERATION', COUNTRY_CODE, COUNT(DISTINCT TIMESTAMP)
    FROM RAW.GENERATION
    WHERE TO_DATE(CONVERT_TIMEZONE('Europe/Budapest', TIMESTAMP)) = $run_date
    GROUP BY COUNTRY_CODE
    UNION ALL
    SELECT 'DAY_AHEAD_PRICES', COUNTRY_CODE, COUNT(DISTINCT TIMESTAMP)
    FROM RAW.DAY_AHEAD_PRICES
    WHERE TO_DATE(CONVERT_TIMEZONE('Europe/Budapest', TIMESTAMP)) = $run_date
    GROUP BY COUNTRY_CODE
),
expected AS (
    SELECT d.DATASET, c.COUNTRY_CODE
    FROM (VALUES ('LOAD'), ('LOAD_FORECAST'), ('GENERATION'), ('DAY_AHEAD_PRICES')) AS d(DATASET)
    CROSS JOIN (VALUES ('HU'), ('AT'), ('SK')) AS c(COUNTRY_CODE)
)
SELECT
    e.DATASET,
    e.COUNTRY_CODE,
    COALESCE(n.INTERVALS, 0) AS INTERVALS,
    IFF(COALESCE(n.INTERVALS, 0) = $expected_intervals, 'OK', 'FAIL') AS STATUS
FROM expected e
LEFT JOIN counts n
  ON e.DATASET = n.DATASET AND e.COUNTRY_CODE = n.COUNTRY_CODE
ORDER BY e.DATASET, e.COUNTRY_CODE;
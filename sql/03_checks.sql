-- Daily price record counts
SELECT
    COUNTRY_CODE,
    TO_DATE(CONVERT_TIMEZONE('Europe/Budapest', TIMESTAMP)) AS DATE,
    COUNT(*) AS PRICE_RECORDS
FROM ENERGY_DB.RAW.DAY_AHEAD_PRICES
GROUP BY COUNTRY_CODE, DATE
ORDER BY COUNTRY_CODE, DATE;



    COUNTRY_CODE,
    COUNT(*) AS ROW_COUNT,
    MIN(TIMESTAMP) AS FIRST_TIMESTAMP,
    MAX(TIMESTAMP) AS LAST_TIMESTAMP
FROM ENERGY_DB.RAW.LOAD
GROUP BY COUNTRY_CODE

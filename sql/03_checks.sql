    MIN(DATE(CONVERT_TIMEZONE('Europe/Budapest', TIMESTAMP))),
    MAX(DATE(CONVERT_TIMEZONE('Europe/Budapest', TIMESTAMP)))
FROM RAW.DAY_AHEAD_PRICES


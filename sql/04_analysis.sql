USE WAREHOUSE ENERGY_WH;
USE DATABASE ENERGY_DB;


-- ==========================================================
-- 1. LOAD FORECAST ANALYSIS
-- ==========================================================

-- Reuse the forecast-error calculation defined in 02_view.sql.
-- Keep this view name because the Streamlit dashboard queries it.
CREATE OR REPLACE VIEW ENERGY_DB.ANALYTICS.LOAD_FORECAST_ANALYSIS AS
SELECT
    TIMESTAMP,
    COUNTRY_CODE,
    ACTUAL_LOAD_MW,
    FORECAST_LOAD_MW,
    FORECAST_ERROR_MW,
    ABSOLUTE_ERROR_MW
FROM ENERGY_DB.ANALYTICS.LOAD_FORECAST_ERROR;

-- Overall mean absolute error (MAE) by country
SELECT
    COUNTRY_CODE,
    COUNT(*) AS TOTAL_ROWS,
    ROUND(AVG(ABSOLUTE_ERROR_MW), 2) AS MAE_MW,
    ROUND(AVG(ACTUAL_LOAD_MW), 2) AS AVG_ACTUAL_LOAD_MW,
    ROUND(
        AVG(ABSOLUTE_ERROR_MW) / NULLIF(AVG(ACTUAL_LOAD_MW), 0) * 100,
        2
    ) AS MAE_PERCENT
FROM ENERGY_DB.ANALYTICS.LOAD_FORECAST_ANALYSIS
GROUP BY COUNTRY_CODE
ORDER BY COUNTRY_CODE;

-- Ten country-days with the largest normalized forecast error
SELECT *
FROM ENERGY_DB.ANALYTICS.FORECAST_ACCURACY_BY_COUNTRY
ORDER BY MAE_PERCENT DESC
LIMIT 10;

-- Compare actual and forecast load by local hour on one example day
SELECT
    HOUR(CONVERT_TIMEZONE('Europe/Budapest', TIMESTAMP)) AS LOCAL_HOUR,
    ROUND(AVG(ACTUAL_LOAD_MW), 0) AS ACTUAL,
    ROUND(AVG(FORECAST_LOAD_MW), 0) AS FORECAST,
    ROUND(AVG(FORECAST_ERROR_MW), 0) AS ERROR
FROM ENERGY_DB.ANALYTICS.LOAD_FORECAST_ANALYSIS
WHERE COUNTRY_CODE = 'AT'
  AND TO_DATE(CONVERT_TIMEZONE('Europe/Budapest', TIMESTAMP)) = '2026-07-24'
GROUP BY LOCAL_HOUR
ORDER BY LOCAL_HOUR;

-- Monthly forecast bias: negative errors mean forecasts were too high
SELECT
    COUNTRY_CODE,
    DATE_TRUNC('month', CONVERT_TIMEZONE('Europe/Budapest', TIMESTAMP))::DATE AS MONTH_START,
    ROUND(AVG(FORECAST_ERROR_MW), 0) AS AVG_ERROR_MW,
    ROUND(100 * COALESCE(COUNT_IF(FORECAST_ERROR_MW < 0), 0) / NULLIF(COUNT(*), 0), 1)
        AS PCT_FORECAST_TOO_HIGH
FROM ENERGY_DB.ANALYTICS.LOAD_FORECAST_ANALYSIS
GROUP BY COUNTRY_CODE, MONTH_START
ORDER BY COUNTRY_CODE, MONTH_START;

-- Daily forecast accuracy data
SELECT *
FROM ENERGY_DB.ANALYTICS.FORECAST_ACCURACY_BY_COUNTRY
ORDER BY COUNTRY_CODE, LOCAL_DATE;


-- ==========================================================
-- 2. ELECTRICITY GENERATION MIX
-- ==========================================================

-- Total reported generation energy by source.
-- Quarter-hourly power in MW is converted to MWh using 0.25 hours.
SELECT
    ENERGY_SOURCE,
    COUNT(*) AS TOTAL_ROWS,
    ROUND(SUM(GENERATION_MW) * 0.25, 2) AS TOTAL_GENERATION_MWH
FROM ENERGY_DB.RAW.GENERATION
GROUP BY ENERGY_SOURCE
ORDER BY ENERGY_SOURCE;


-- Review the distribution of sources among categories
SELECT
    ENERGY_CATEGORY,
    COUNT(DISTINCT ENERGY_SOURCE) AS SOURCE_COUNT,
    COUNT(*) AS TOTAL_ROWS
FROM ENERGY_DB.ANALYTICS.GENERATION_MIX
GROUP BY ENERGY_CATEGORY
ORDER BY ENERGY_CATEGORY;

-- Total reported generation and relative share by country and category
WITH category_totals AS (
    SELECT
        COUNTRY_CODE,
        ENERGY_CATEGORY,
        SUM(GENERATION_MW) * 0.25 AS GENERATION_MWH
    FROM ENERGY_DB.ANALYTICS.GENERATION_MIX
    GROUP BY COUNTRY_CODE, ENERGY_CATEGORY
)
SELECT
    COUNTRY_CODE,
    ENERGY_CATEGORY,
    ROUND(GENERATION_MWH, 2) AS GENERATION_MWH,
    ROUND(
        GENERATION_MWH /
        NULLIF(SUM(GENERATION_MWH) OVER (PARTITION BY COUNTRY_CODE), 0) * 100,
        2
    ) AS SHARE_PERCENT
FROM category_totals
ORDER BY COUNTRY_CODE, SHARE_PERCENT DESC;

-- Daily generation in MWh and percentage share (Budapest local day)
CREATE OR REPLACE VIEW ENERGY_DB.ANALYTICS.DAILY_GENERATION_MIX AS
WITH daily_totals AS (
    SELECT
        COUNTRY_CODE,
        TO_DATE(CONVERT_TIMEZONE('Europe/Budapest', TIMESTAMP)) AS DATE,
        ENERGY_CATEGORY,
        SUM(GENERATION_MW * 0.25) AS GENERATION_MWH
    FROM ENERGY_DB.ANALYTICS.GENERATION_MIX
    GROUP BY COUNTRY_CODE,
             TO_DATE(CONVERT_TIMEZONE('Europe/Budapest', TIMESTAMP)),
             ENERGY_CATEGORY
)
SELECT
    COUNTRY_CODE,
    DATE,
    ENERGY_CATEGORY,
    ROUND(GENERATION_MWH, 2) AS GENERATION_MWH,
    ROUND(
        GENERATION_MWH /
        NULLIF(SUM(GENERATION_MWH) OVER (PARTITION BY COUNTRY_CODE, DATE), 0) * 100,
        2
    ) AS SHARE_PERCENT
FROM daily_totals;

-- Inspect the daily generation mix for one example date
SELECT
    COUNTRY_CODE,
    DATE,
    ENERGY_CATEGORY,
    GENERATION_MWH,
    SHARE_PERCENT
FROM ENERGY_DB.ANALYTICS.DAILY_GENERATION_MIX
WHERE DATE = '2026-10-01'
ORDER BY COUNTRY_CODE, SHARE_PERCENT DESC;

-- Check the date coverage of the daily generation view
SELECT
    COUNTRY_CODE,
    COUNT(DISTINCT DATE) AS DAYS_AVAILABLE,
    MIN(DATE) AS FIRST_DATE,
    MAX(DATE) AS LAST_DATE
FROM ENERGY_DB.ANALYTICS.DAILY_GENERATION_MIX
GROUP BY COUNTRY_CODE
ORDER BY COUNTRY_CODE;


-- ==========================================================
-- 3. ELECTRICITY CONSUMPTION AND MARKET PRICES
-- ==========================================================

-- Daily average electricity load by country
SELECT
    TO_DATE(CONVERT_TIMEZONE('Europe/Budapest', TIMESTAMP)) AS DATE,
    COUNTRY_CODE,
    ROUND(AVG(ACTUAL_LOAD_MW), 2) AS AVG_LOAD_MW
FROM ENERGY_DB.RAW.LOAD
GROUP BY DATE, COUNTRY_CODE
ORDER BY DATE, COUNTRY_CODE;

-- Sample of matched 15-minute actual load and day-ahead price records
SELECT
    l.COUNTRY_CODE,
    l.TIMESTAMP,
    l.ACTUAL_LOAD_MW,
    p.PRICE_EUR_MWH
FROM ENERGY_DB.RAW.LOAD l
INNER JOIN ENERGY_DB.RAW.DAY_AHEAD_PRICES p
    ON l.COUNTRY_CODE = p.COUNTRY_CODE
   AND l.TIMESTAMP = p.TIMESTAMP
ORDER BY l.COUNTRY_CODE, l.TIMESTAMP
LIMIT 100;

-- Correlation of 15-minute actual load and day-ahead prices by country
SELECT
    l.COUNTRY_CODE,
    COUNT(*) AS TOTAL_RECORDS,
    ROUND(CORR(l.ACTUAL_LOAD_MW, p.PRICE_EUR_MWH), 3) AS LOAD_PRICE_CORRELATION,
    ROUND(AVG(l.ACTUAL_LOAD_MW), 2) AS AVG_LOAD_MW,
    ROUND(AVG(p.PRICE_EUR_MWH), 2) AS AVG_PRICE_EUR_MWH
FROM ENERGY_DB.RAW.LOAD l
INNER JOIN ENERGY_DB.RAW.DAY_AHEAD_PRICES p
    ON l.COUNTRY_CODE = p.COUNTRY_CODE
   AND l.TIMESTAMP = p.TIMESTAMP
GROUP BY l.COUNTRY_CODE
ORDER BY l.COUNTRY_CODE;

-- Daily average load and price for each country
SELECT
    TO_DATE(CONVERT_TIMEZONE('Europe/Budapest', l.TIMESTAMP)) AS DATE,
    l.COUNTRY_CODE,
    ROUND(AVG(l.ACTUAL_LOAD_MW), 2) AS AVG_LOAD_MW,
    ROUND(AVG(p.PRICE_EUR_MWH), 2) AS AVG_PRICE_EUR_MWH
FROM ENERGY_DB.RAW.LOAD l
INNER JOIN ENERGY_DB.RAW.DAY_AHEAD_PRICES p
    ON l.COUNTRY_CODE = p.COUNTRY_CODE
   AND l.TIMESTAMP = p.TIMESTAMP
GROUP BY DATE, l.COUNTRY_CODE
ORDER BY DATE, l.COUNTRY_CODE;

-- Correlation of daily electricity prices with renewable share and demand
SELECT
    COUNTRY_CODE,
    COUNT(*) AS DAYS,
    ROUND(CORR(AVG_PRICE, RENEWABLE_SHARE_PERCENT), 2) AS CORR_PRICE_RENEWABLES,
    ROUND(CORR(AVG_PRICE, AVG_LOAD_MW), 2) AS CORR_PRICE_LOAD
FROM ENERGY_DB.ANALYTICS.DAILY_MARKET_SUMMARY
GROUP BY COUNTRY_CODE
ORDER BY COUNTRY_CODE;

-- Typical local-hour load and price profiles
SELECT *
FROM ENERGY_DB.ANALYTICS.HOURLY_PROFILE
ORDER BY COUNTRY_CODE, LOCAL_HOUR;
